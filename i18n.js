/* ===== Motor de idiomas (PT padrão · EN · ES) =====
   O português fica escrito no HTML. Para EN/ES, cada texto é trocado pela
   tradução do dicionário acima; para PT, o texto original é restaurado. */
(function () {
  const LANGS = { pt: 'pt-BR', en: 'en', es: 'es' };
  const ATTRS = ['alt', 'aria-label', 'title'];
  const origText = new WeakMap();   // nó de texto -> texto original
  const origAttr = new WeakMap();   // elemento -> { attr: original }
  const origMeta = new Map();       // meta -> content original
  let origTitle = null;

  const norm = s => s.replace(/\s+/g, ' ').trim();
  const tr = (text, lang) => {
    const entry = I18N_DICT[norm(text)];
    return entry && entry[lang] ? entry[lang] : null;
  };

  function detect() {
    try { const s = localStorage.getItem('lang'); if (LANGS[s]) return s; } catch (e) {}
    const n = (navigator.language || 'pt').slice(0, 2).toLowerCase();
    return LANGS[n] ? n : 'pt';
  }

  function applyText(lang) {
    const walker = document.createTreeWalker(document.body, NodeFilter.SHOW_TEXT, {
      acceptNode(n) {
        const p = n.parentElement;
        if (!p || p.closest('script,style,pre,.code,[data-no-i18n]')) return NodeFilter.FILTER_REJECT;
        return NodeFilter.FILTER_ACCEPT;
      }
    });
    let n;
    while ((n = walker.nextNode())) {
      if (!origText.has(n)) origText.set(n, n.nodeValue);
      const orig = origText.get(n);
      if (lang === 'pt') { n.nodeValue = orig; continue; }
      const t = tr(orig, lang);
      if (t) {
        const lead = orig.match(/^\s*/)[0], trail = orig.match(/\s*$/)[0];
        n.nodeValue = lead + t + trail;
      } else n.nodeValue = orig;
    }
  }

  function applyAttrs(lang) {
    document.querySelectorAll(ATTRS.map(a => '[' + a + ']').join(',')).forEach(el => {
      if (el.closest('.lang')) return; // nomes dos idiomas ficam no próprio idioma
      let store = origAttr.get(el); if (!store) { store = {}; origAttr.set(el, store); }
      ATTRS.forEach(a => {
        if (!el.hasAttribute(a)) return;
        if (!(a in store)) store[a] = el.getAttribute(a);
        const t = lang === 'pt' ? null : tr(store[a], lang);
        el.setAttribute(a, t || store[a]);
      });
    });
  }

  function applyHead(lang) {
    if (origTitle === null) origTitle = document.title;
    document.title = (lang !== 'pt' && tr(origTitle, lang)) || origTitle;
    document.querySelectorAll('meta[name="description"],meta[property="og:title"],meta[property="og:description"]').forEach(m => {
      if (!origMeta.has(m)) origMeta.set(m, m.getAttribute('content'));
      const o = origMeta.get(m);
      m.setAttribute('content', (lang !== 'pt' && tr(o, lang)) || o);
    });
  }

  function setLang(lang, save) {
    if (!LANGS[lang]) lang = 'pt';
    document.documentElement.lang = LANGS[lang];
    applyText(lang); applyAttrs(lang); applyHead(lang);
    document.querySelectorAll('.lang [data-lang]').forEach(b =>
      b.setAttribute('aria-pressed', String(b.dataset.lang === lang)));
    if (save) { try { localStorage.setItem('lang', lang); } catch (e) {} }
  }

  document.querySelectorAll('.lang [data-lang]').forEach(b =>
    b.addEventListener('click', () => setLang(b.dataset.lang, true)));
  setLang(detect(), false);
})();
